# 小整数缓存的"坑"：字面量合并 vs 运行时新建
a = 257
b = 257
print("同一代码对象里，字面量 257 被合并:", a is b)   # True（编译器优化）

x = int("257")
y = int("257")
print("运行时各自创建:", x is y)                     # False（缓存之外）
